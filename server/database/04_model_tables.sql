  `thumb_url` VARCHAR(500) NOT NULL DEFAULT '',
  `watermark_url` VARCHAR(500) NOT NULL DEFAULT '',
  `sort` INT UNSIGNED NOT NULL DEFAULT 0,
  `is_cover` TINYINT UNSIGNED NOT NULL DEFAULT 0,
