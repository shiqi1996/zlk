SET NAMES utf8mb4;

DROP TABLE IF EXISTS `score_rule_config`;
CREATE TABLE `score_rule_config` (
  `id` BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
  `rule_name` VARCHAR(50) NOT NULL DEFAULT '',
  `rule_code` VARCHAR(50) NOT NULL DEFAULT '',
  `scene` VARCHAR(50) NOT NULL DEFAULT '',
  `score_amount` INT NOT NULL DEFAULT 0,
  `daily_limit` INT UNSIGNED NOT NULL DEFAULT 0,
  `expire_days` INT UNSIGNED NOT NULL DEFAULT 0,
  `expire_remind_days` VARCHAR(50) NOT NULL DEFAULT '',
  `description` VARCHAR(255) NOT NULL DEFAULT '',
  `site_id` BIGINT UNSIGNED NOT NULL DEFAULT 1,
  `status` TINYINT UNSIGNED NOT NULL DEFAULT 1,
  `create_time` DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  `update_time` DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  `delete_time` BIGINT UNSIGNED NOT NULL DEFAULT 0,
  PRIMARY KEY (`id`),
  UNIQUE KEY `uk_rule_code` (`site_id`, `rule_code`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='积分规则配置表';

DROP TABLE IF EXISTS `score_log`;
CREATE TABLE `score_log` (
  `id` BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
  `user_id` BIGINT UNSIGNED NOT NULL DEFAULT 0,
  `rule_code` VARCHAR(50) NOT NULL DEFAULT '',
  `scene` VARCHAR(50) NOT NULL DEFAULT '',
  `amount` INT NOT NULL DEFAULT 0,
  `balance` INT UNSIGNED NOT NULL DEFAULT 0,
  `remark` VARCHAR(255) NOT NULL DEFAULT '',
  `expire_time` DATETIME DEFAULT NULL,
  `site_id` BIGINT UNSIGNED NOT NULL DEFAULT 1,
  `create_time` DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (`id`),
  KEY `idx_user_id` (`user_id`),
  KEY `idx_scene` (`scene`),
  KEY `idx_create_time` (`create_time`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='积分流水表';

DROP TABLE IF EXISTS `score_expire_config`;
CREATE TABLE `score_expire_config` (
  `id` BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
  `expire_days` INT UNSIGNED NOT NULL DEFAULT 0,
  `expire_remind_days` VARCHAR(50) NOT NULL DEFAULT '',
  `auto_clean` TINYINT UNSIGNED NOT NULL DEFAULT 0,
  `site_id` BIGINT UNSIGNED NOT NULL DEFAULT 1,
  `create_time` DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  `update_time` DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  `delete_time` BIGINT UNSIGNED NOT NULL DEFAULT 0,
  PRIMARY KEY (`id`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='积分过期配置表';

DROP TABLE IF EXISTS `score_risk_log`;
CREATE TABLE `score_risk_log` (
  `id` BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
  `user_id` BIGINT UNSIGNED NOT NULL DEFAULT 0,
  `risk_type` VARCHAR(50) NOT NULL DEFAULT '',
  `risk_detail` JSON DEFAULT NULL,
  `action` VARCHAR(20) NOT NULL DEFAULT '',
  `site_id` BIGINT UNSIGNED NOT NULL DEFAULT 1,
  `create_time` DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (`id`),
  KEY `idx_user_id` (`user_id`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='积分风控日志表';

DROP TABLE IF EXISTS `vip_config`;
