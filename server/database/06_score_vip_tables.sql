DROP TABLE IF EXISTS `vip_order`;
CREATE TABLE `vip_order` (
  `id` BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
  `order_no` VARCHAR(64) NOT NULL DEFAULT '',
